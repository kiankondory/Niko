namespace Niko.Core.Domain;

/// <summary>
/// وضعیت یک میل‌استون نسبت به استریک فعلی.
/// </summary>
public enum MilestoneStatus
{
    /// <summary>دستیابی‌شده (آستانهٔ کمتر یا مساوی میل‌استون فعلی).</summary>
    Completed = 0,

    /// <summary>میل‌استون فعلی/هدف فعال (آستانهٔ بعدی).</summary>
    Current = 1,

    /// <summary>آینده (آستانهٔ بعد از هدف فعال).</summary>
    Upcoming = 2,
}

/// <summary>
/// یک میل‌استون با آستانهٔ روز و وضعیت آن.
/// </summary>
public sealed record MilestoneInfo(
    int ThresholdDays,
    MilestoneStatus Status);
