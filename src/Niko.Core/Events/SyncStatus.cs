namespace Niko.Core.Events;

/// <summary>
/// وضعیت همگام‌سازی هر رویداد محلی.
/// </summary>
public enum SyncStatus
{
    /// <summary>در صف همگام‌سازی در انتظار ارسال.</summary>
    Pending = 0,

    /// <summary>با موفقیت همگام شده است.</summary>
    InSync = 1,

    /// <summary>ارسال با شکست مواجه شده و در انتظار تلاش مجدد است.</summary>
    Failed = 2,
}
