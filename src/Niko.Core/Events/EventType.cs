namespace Niko.Core.Events;

/// <summary>
/// انواع رویدادهای پشتیبانی‌شده. مقادیر باید پایدار بمانند (بر پایهٔ اعداد) تا
/// قرارداد سریال‌شده بین پلتفرم‌ها سازگار باشد.
/// </summary>
public enum EventType
{
    /// <summary>ثبت مصرف (سیگار کشیده شد).</summary>
    Smoked = 1,

    /// <summary>ثبت مقاومت در برابر مصرف.</summary>
    Resisted = 2,

    /// <summary>ثبت هوس/میل به مصرف.</summary>
    Craving = 3,

    /// <summary>ثبت اقدامی در جریان «نبرد با هوس».</summary>
    CravingAction = 4,

    /// <summary>ایجاد پروفایل کاربر.</summary>
    ProfileCreated = 10,

    /// <summary>تغییر تنظیمات کاربر.</summary>
    SettingsChanged = 11,

    /// <summary>ویرایش یک رویداد قبلی (برای ممیزی).</summary>
    Edited = 20,

    /// <summary>حذف منطقی یک رویداد قبلی (برای ممیزی).</summary>
    Deleted = 21,
}
