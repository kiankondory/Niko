namespace Niko.Core.Abstractions;

/// <summary>
/// سرویس محلی‌سازی مبتنی بر کلید. پیاده‌سازی، منبع‌ها را برای locale فعال می‌یابد.
/// </summary>
public interface ILocalizationService
{
    /// <summary>وقتی locale فعال تغییر می‌کند.</summary>
    event EventHandler? LocaleChanged;

    /// <summary>
    /// ترجمهٔ یک کلید با پارامترهای ساخت‌یافتهٔ اختیاری.
    /// در صورت نبود کلید، زنجیرهٔ fallback بررسی می‌شود و در نهایت کلید گزارش می‌شود.
    /// </summary>
    string GetString(string key, params object[] args);

    /// <summary>locale فعال کنونی (مانند fa، en-US).</summary>
    string CurrentLocale { get; }

    /// <summary>تغییر locale فعال.</summary>
    void SetLocale(string locale);
}
