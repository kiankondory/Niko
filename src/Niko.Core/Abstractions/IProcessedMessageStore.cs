/// <summary>
/// قرارداد ذخیرهٔ شناسهٔ پیام‌های پردازش‌شده.
/// </summary>
public interface IProcessedMessageStore
{
    /// <summary>
    /// اگر شناسه قبلاً پردازش نشده باشد true برمی‌گرداند و آن را ثبت می‌کند؛
    /// در صورت تکراری بودن false.
    /// </summary>
    Task<bool> TryMarkProcessedAsync(string messageId, CancellationToken ct = default);
}
